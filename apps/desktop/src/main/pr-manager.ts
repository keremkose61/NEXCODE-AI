import { PRReviewSummary } from '@nexcode/shared';
import { gitService } from './git-service';

export class PRManager {
  public async generateReview(workspacePath: string, baseBranch = 'master'): Promise<PRReviewSummary> {
    const branches = await gitService.getBranches(workspacePath);
    const status = await gitService.getStatus(workspacePath);
    const currentBranch = branches.current || 'feature-branch';

    const changedFiles = status.files.map((f) => f.path);
    const fileReviews: PRReviewSummary['fileReviews'] = [];

    let overallRisk: 'low' | 'medium' | 'high' = 'low';

    for (const file of changedFiles) {
      const diff = await gitService.getDiff(workspacePath, file);
      const suggestions: string[] = [];

      // Static code quality heuristics
      if (diff.modified.includes('eval(')) {
        suggestions.push('Security Alert: Avoid using `eval()`. Use safer parsing alternatives.');
        overallRisk = 'high';
      }
      if (diff.modified.includes('any')) {
        suggestions.push('Type Safety: Consider replacing `any` with explicit TypeScript types or generics.');
      }
      if (diff.modified.includes('console.log(')) {
        suggestions.push('Cleanup: Detected debug `console.log` statement.');
      }
      if (diff.modified.includes('password') && diff.modified.includes('=')) {
        suggestions.push('Security Warning: Potential plaintext secret/credential detected.');
        overallRisk = 'high';
      }

      fileReviews.push({
        filePath: file,
        suggestions: suggestions.length > 0 ? suggestions : ['Clean code, no obvious anti-patterns detected.'],
        status: suggestions.length > 0 ? 'has_notes' : 'clean'
      });
    }

    const title = `feat(${currentBranch}): Automated Pull Request & Code Review`;
    const description = `## 🔍 Local AI Code Review Summary

- **Source Branch:** \`${currentBranch}\`
- **Target Branch:** \`${baseBranch}\`
- **Changed Files:** ${changedFiles.length} file(s)
- **Risk Assessment:** ${overallRisk.toUpperCase()}

### 📋 File Analysis
${fileReviews
  .map(
    (fr) =>
      `* **\`${fr.filePath}\`**: ${fr.suggestions.map((s) => `\n    - ${s}`).join('')}`
  )
  .join('\n')}

---
*Generated by NEXCODE AI Local PR Reviewer (100% Offline)*`;

    return {
      title,
      description,
      branch: currentBranch,
      baseBranch,
      summary: `Reviewed ${changedFiles.length} modified file(s). Risk level: ${overallRisk}.`,
      riskLevel: overallRisk,
      fileReviews
    };
  }
}

export const prManager = new PRManager();
